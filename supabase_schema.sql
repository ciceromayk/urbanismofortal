-- Execute no SQL Editor do Supabase
create table if not exists public.lancamentos (
  id bigint generated by default as identity primary key,
  nome text not null,
  bairro text not null,
  construtora text not null,
  endereco text default '',
  latitude double precision,
  longitude double precision,
  unidades_total integer default 0,
  unidades_disponiveis integer default 0,
  area_media_m2 double precision,
  preco_medio double precision,
  faixa_preco text default '',
  previsao_entrega text default '',
  descricao text default '',
  link_tabela_disponibilidade text default '',
  link_plantas text default '',
  link_imagens text default '',
  telefone_comercial text default '',
  disponibilidade_tipologia text default '[]',
  atualizado_em timestamptz default now(),
  constraint disp_le_total check (unidades_disponiveis <= unidades_total)
);

-- Leitura pública; escrita apenas com a chave service_role (usada no app via secrets).
alter table public.lancamentos enable row level security;
create policy "leitura publica" on public.lancamentos for select using (true);
